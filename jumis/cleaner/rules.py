# jumis/cleaner/rules.py
"""
Правила «что считается мусором».

Чистые функции без зависимостей: их использует и уборка (janitor),
и ingest (чтобы не векторизовать мусор), и тесты.

Главный принцип: НИЧЕГО с цифрами, ссылками, @ и телефонами не считается
мусором, даже если оно короткое. «700₽», «завтра в 15», «+79161234567» —
это информация, а не болтовня.
"""
import re


# Регулярка «в сообщении есть ценность»: цифра, ссылка, юзернейм, e-mail.
_VALUE_RE = re.compile(r"[0-9]|https?://|www\.|@\w", re.IGNORECASE)

# Только буквы/цифры, в нижнем регистре, ё -> е.
_NORM_RE = re.compile(r"[^а-яa-z0-9]")

# Сообщения, которые точно не несут смысла, если в них нет цифр.
# Сравнение идёт по нормализованному тексту (без пунктуации и эмодзи).
STOP_PHRASES = {
    # приветствия / прощания
    "привет", "приветик", "приветствую", "здравствуйте", "здравствуй",
    "хай", "хелло", "ку", "доброеутро", "доброеутречко", "добрыйдень",
    "добрыйвечер", "добройночи", "спокойнойночи", "пока", "до", "досвязи",
    "досвидания", "бб", "бай",
    # подтверждения
    "ок", "оке", "окей", "океей", "окэ", "океда", "ага", "агась", "угу",
    "да", "даа", "дааа", "конечно", "само", "собой", "разумеется",
    "хорошо", "хор", "лады", "ладно", "принял", "принято", "понял", "поняла",
    "ясно", "чисто", "верно", "точно", "именно", "согласен", "согласна",
    # благодарности
    "спасибо", "спасиб", "спс", "благодарю", "спасибочки", "пасиб",
    "спасибоогромное", "спасибобольшое",
    # реакции
    "угу", "дада", "нее", "неа", "ха", "хаха", "хахаха",
    "ахах", "ахаха", "хах", "хех", "лол", "кек", "ору", "смешно",
    "ой", "о", "ооо", "ааа", "эх", "ух", "ого", "вау", "супер", "класс",
    "круто", "капец", "жесть", "ничего", "себе", "дела", "ща", "сейчас",
    "молодец", "умница", "красава", "красавчик",
    # короткие вопросы-пустышки
    "дома", "домали", "тыгде", "где", "ау", "аууу", "тытут", "тут",
    "чёт", "че", "что", "как", "какдела", "какдила", "дела", "каксам",
    "чтоделаешь", "тыкак", "какты", "всёок", "всеок", "всеокей", "всёокей",
    "всехорошо", "всёнорм", "всенорм",
    # эмодзи-слова (на случай, если нормализация не сработала)
    "лайк", "плюс", "плюсую", "плюсодин",
}

# Начала фраз, которые считаются болтовнёй в любой форме
# ("спокойной ночи, и я♥️💤" и подобные вариации).
STOP_PREFIXES = (
    "доброеутро", "доброеутречко", "спокойнойночи", "добройночи",
    "добрыйдень", "добрыйвечер", "здравствуйте", "спасибо",
)

# Короткие слова из 1-2 букв, которые всё-таки несут смысл.
SHORT_MEANINGFUL = {"не", "ну", "мы", "вы", "он", "я", "ты", "ей", "мне"}

# Сервисные заглушки ingest/STT — текста в них нет.
SERVICE_PREFIX = "["

# Сколько символов текста имеет смысл хранить в дайджесте и индексировать.
MAX_SHORT_LEN = 40


def normalize(text: str) -> str:
    """Нижний регистр, ё->е, выкинуть всё кроме а-я/a-z/0-9."""
    return _NORM_RE.sub("", (text or "").lower().replace("ё", "е"))


def has_value(text: str) -> bool:
    """Есть ли в тексте цифра, ссылка, @ или почта — то есть смысловая зацепка."""
    return bool(_VALUE_RE.search(text or ""))


def is_media_without_text(msg_type: str, content: str) -> bool:
    """Медиа без расшифровки: фото/стикер/видео/аудио/документ без caption."""
    return (msg_type or "text").lower() not in ("text", "voice") and not (content or "").strip()


def is_junk(content: str, msg_type: str = "text") -> bool:
    """
    Мусор ли сообщение. True -> не векторизуем и (для истории) удаляем.

    Учитываются: пустой текст, медиа без текста, сервисные заглушки,
    только пунктуация/эмодзи, стоп-фразы, огрызки из 1-2 символов.
    Любое сообщение с цифрой/ссылкой/@ мусором не считается.
    """
    text = (content or "").strip()
    mtype = (msg_type or "text").lower()

    # 1. Медиа (фото, стикер, видео, аудио, документ): ценно только если в подписи
    #    есть цифра/ссылка. «👍» и пустая подпись — не история, а мусор.
    if mtype not in ("text", "voice"):
        return not (text and has_value(text))

    # 2. Пусто или сервисная заглушка вида "[Ошибка расшифровки голосового]".
    if not text or text.startswith(SERVICE_PREFIX):
        return True

    # 3. Есть цифры/ссылки/@ — это ценность, дальше не смотрим.
    if has_value(text):
        return False

    norm = normalize(text)

    # 4. Только пунктуация или эмодзи: ")", ")))", "👍".
    if not norm:
        return True

    # 5. Известные пустышки.
    if norm in STOP_PHRASES:
        return True

    # 6. Начала фраз-ритуалов («спокойной ночи, и я♥️💤»).
    if any(norm.startswith(prefix) for prefix in STOP_PREFIXES):
        return True

    # 7. Огрызки из одной-двух букв без смысла.
    if len(norm) <= 2 and norm not in SHORT_MEANINGFUL:
        return True

    return False


def is_searchable(content: str, msg_type: str = "text") -> bool:
    """Обратная операция: стоит ли вообще считать вектор для сообщения."""
    return not is_junk(content, msg_type)
